def add(a, b):
    return a + b


def subtract(a, b):
    return a - b


def multiply(a, b):
    return a * b


def divide(a, b):
    return a / b


def power(a, b):
    """Return a raised to the power of b.

    Args:
        a (int or float): The base number.
        b (int or float): The exponent.

    Returns:
        int or float: The result of a ** b.
    """
    return a ** b


def square(a):
    """Return the square of a number.

    Args:
        a (int or float): The number to square.

    Returns:
        int or float: The result of a * a.
    """
    return a * a


def cube(a):
    """Return the cube of a number.

    Args:
        a (int or float): The number to cube.

    Returns:
        int or float: The result of a ** 3.
    """
    return a ** 3
